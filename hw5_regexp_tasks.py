import re

"""#### **Задание 1**

*это пример*

Получите фразу `['Ваш текст']`

> Simple is better then complex <br/>
> *(c) Дзен Python*

"""

pattern = r"\bВаш текст\b"

text = 'Ваш текст'
print(re.findall(pattern = pattern, string = text))

"""#### **Задание 2**

Получите все цифры в строке (в чем разница между цифрами и числами?).

Ответ: `['2', '5', '1', '2']`

"""

pattern = r"\d{1}"
#Цифра - это один единственный символ, из которого мы строим числа.
#Цифры от 0 до 9. напрмер число 25 это число, состоит из двух цифр 2 и 5.
#Паттерн r"\d" находит каждый символ по отдельности, его применяют для поиска цифр,
# а для чисел паттерн r"\d+", склеивает цифры вместе

text = 'Никто не подскажет, какова масса 25 атомов  углерода-12 в дальтонах?'
print(re.findall(pattern = pattern, string = text))

"""#### **Задание 3**

Получите все буквы в строке.

Ответ: `['О', 'л', 'ь', 'г', 'а']`

"""

pattern = r"[а-яА-ЯёЁ]"

text = 'Ольга'
print(re.findall(pattern = pattern, string = text))

